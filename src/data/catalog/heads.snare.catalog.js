function snareHeadItem({
  id,
  category,
  brand,
  model,
  finish,
  ply,
  milTotal,
  dot = 'None',
  controlRing = false,
  dryVents = false,
  feel = '',
  tonalSummary = '',
  dryness = 3,
  durability = 3,
  tuningRange = 'Wide',
  sensitivity = null,
  notes = '',
  vendors = {},
  tags = [],
  sourceMeta = [],
}) {
  return createReferenceCatalogItem({
    id,
    category,
    label: `${brand} ${model}`,
    brand,
    model,
    facts: {
      finish: createCatalogFact({
        value: finish,
        confidence: FACT_CONFIDENCE.HIGH,
      }),
      ply: createCatalogFact({
        value: ply,
        confidence: FACT_CONFIDENCE.HIGH,
      }),
      milTotal: createCatalogFact({
        value: milTotal,
        unit: 'mil',
        confidence: FACT_CONFIDENCE.HIGH,
      }),
      dot: createCatalogFact({
        value: dot,
        confidence: FACT_CONFIDENCE.MEDIUM,
      }),
      controlRing: createCatalogFact({
        value: controlRing,
        confidence: FACT_CONFIDENCE.MEDIUM,
      }),
      dryVents: createCatalogFact({
        value: dryVents,
        confidence: FACT_CONFIDENCE.MEDIUM,
      }),
      tuningRange: createCatalogFact({
        value: tuningRange,
        confidence: FACT_CONFIDENCE.LOW,
        notes: 'Normalized Ober compatibility field.',
      }),
      dryness: createCatalogFact({
        value: dryness,
        unit: '1-5',
        confidence: FACT_CONFIDENCE.LOW,
        notes: 'Normalized Ober heuristic scale; not a manufacturer metric.',
      }),
      durability: createCatalogFact({
        value: durability,
        unit: '1-5',
        confidence: FACT_CONFIDENCE.LOW,
        notes: 'Normalized Ober heuristic scale; not a manufacturer metric.',
      }),
      sensitivity: createCatalogFact({
        value: sensitivity,
        unit: '1-5',
        confidence: FACT_CONFIDENCE.LOW,
        notes: 'Normalized Ober heuristic scale; mainly for reso heads.',
      }),
      vendors: createCatalogFact({
        value: vendors,
        confidence: FACT_CONFIDENCE.MEDIUM,
      }),
    },
    tonalDescriptors: {
      feel: createCatalogFact({
        value: feel,
        confidence: FACT_CONFIDENCE.LOW,
        notes: 'Ober editorial descriptor.',
      }),
      tonalSummary: createCatalogFact({
        value: tonalSummary,
        confidence: FACT_CONFIDENCE.LOW,
        notes: 'Ober editorial descriptor.',
      }),
    },
    compatibility: {
      useCases: createCatalogFact({
        value: tags,
        confidence: FACT_CONFIDENCE.LOW,
      }),
    },
    sourceMeta,
    tags,
    notes,
  });
}

