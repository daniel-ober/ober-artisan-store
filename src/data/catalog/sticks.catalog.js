function stickItem({
  id,
  brand,
  model,
  aliases = [],
  material,
  tip,
  tipMaterial = 'wood',
  weightClass,
  balance,
  diameter,
  length,
  grip,
  tack,
  feel = '',
  tonalSummary = '',
  durabilityText = '',
  durabilityScore = 3,
  notes = '',
  vendors = {},
  sourceMeta = [],
  tags = [],
}) {
  return createReferenceCatalogItem({
    id,
    category: REFERENCE_CATEGORIES.STICK,
    label: `${brand} ${model}`,
    brand,
    model,
    aliases,
    facts: {
      material: createCatalogFact({
        value: material,
        confidence: FACT_CONFIDENCE.HIGH,
      }),
      tipShape: createCatalogFact({
        value: tip,
        confidence: FACT_CONFIDENCE.MEDIUM,
      }),
      tipMaterial: createCatalogFact({
        value: tipMaterial,
        confidence: FACT_CONFIDENCE.MEDIUM,
      }),
      weightClass: createCatalogFact({
        value: weightClass,
        confidence: FACT_CONFIDENCE.MEDIUM,
      }),
      balance: createCatalogFact({
        value: balance,
        confidence: FACT_CONFIDENCE.MEDIUM,
      }),
      diameterInches: createCatalogFact({
        value: diameter,
        unit: 'in',
        confidence: FACT_CONFIDENCE.HIGH,
      }),
      lengthInches: createCatalogFact({
        value: length,
        unit: 'in',
        confidence: FACT_CONFIDENCE.HIGH,
      }),
      grip: createCatalogFact({
        value: grip,
        confidence: FACT_CONFIDENCE.MEDIUM,
      }),
      tack: createCatalogFact({
        value: tack,
        unit: '1-5',
        confidence: FACT_CONFIDENCE.LOW,
        notes: 'Ober normalized grip/tack estimate; not manufacturer-standardized.',
      }),
      durabilityText: createCatalogFact({
        value: durabilityText,
        confidence: FACT_CONFIDENCE.LOW,
        notes: 'Normalized Ober descriptor.',
      }),
      durabilityScore: createCatalogFact({
        value: durabilityScore,
        unit: '1-5',
        confidence: FACT_CONFIDENCE.LOW,
        notes: 'Normalized Ober durability estimate; not a manufacturer metric.',
      }),
      vendors: createCatalogFact({
        value: vendors,
        confidence: FACT_CONFIDENCE.MEDIUM,
      }),
    },
    tonalDescriptors: {
      feel: createCatalogFact({
        value: feel,
        confidence: FACT_CONFIDENCE.LOW,
        notes: 'Ober editorial descriptor.',
      }),
      tonalSummary: createCatalogFact({
        value: tonalSummary,
        confidence: FACT_CONFIDENCE.LOW,
        notes: 'Ober editorial descriptor.',
      }),
    },
    compatibility: {
      commonUseCases: createCatalogFact({
        value: tags,
        confidence: FACT_CONFIDENCE.LOW,
        notes: 'Ober tagging for recommendation/ranking.',
      }),
    },
    sourceMeta,
    tags,
    notes,
  });
}

