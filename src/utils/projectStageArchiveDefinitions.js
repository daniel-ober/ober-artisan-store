  PROJECT_STAGE_ARCHIVE_DEFINITIONS[stageKey] || null;

export const getStageSuggestedCaptures = (stageKey) =>
  PROJECT_STAGE_ARCHIVE_DEFINITIONS[stageKey]?.suggestedCaptures || [];

export const getStageAdminCaptureChecklist = (stageKey) =>
  PROJECT_STAGE_ARCHIVE_DEFINITIONS[stageKey]?.adminCaptureChecklist || [];

