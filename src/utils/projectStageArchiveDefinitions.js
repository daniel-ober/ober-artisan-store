const buildCapture = ({
  key,
  label,
  shortLabel,
  mediaType,
  angle = '',
  purpose = '',
  details = [],
  filenameLabel = '',
  visibility = ARCHIVE_VISIBILITY.CUSTOMER,
  required = false,
  adminTask = '',
}) => ({
  key,
  label,
  shortLabel: shortLabel || label,
  mediaType,
  angle,
  purpose,
  details,
  filenameLabel: filenameLabel || label,
  visibility,
  required,
  adminTask: adminTask || label,
});

